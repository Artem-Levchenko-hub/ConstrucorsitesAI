import pytest

from yleum_api.services.generation import source_intent


@pytest.mark.parametrize("prompt", [
    "заполнил анкету а меню нет",
    "Отправили заявку, но в заказах пусто",
    "У клиента не открывается корзина",
    "В MAX после записи ничего не происходит",
    "Почему не работает",
    "Куда добавить услуги?",
    "Подскажи, пожалуйста, где посмотреть заказы",
    "Что делать дальше",
    "Как мне добавить кнопку оплаты?",
    "Проверь, почему меню не появилось",
    "Сколько ещё ждать сборку?",
    "I submitted the form but nothing happened",
    "Where do I add products?",
    "Why can't a customer book a visit",
    "Нет меню после анкеты",
    "Анкета отправилась, меню не составилось",
    "Захожу в корзину, там пусто",
    "Ошибка при сохранении заявки",
    "Заказы пропали",
    "Кнопка оплаты зависла",
    "Не могу записаться",
    "Можно ли добавить запись?",
    "При нажатии выдаёт ошибку",
    "Форма возвращает ошибку 500.",
    "После оплаты появляется ошибка",
    "When I check out it shows an error",
    "На каком этапе сборка",
    "После отправки форма остаётся пустой.",
    "Здравствуйте. Где добавить услуги?",
])
def test_owner_can_ask_for_help_in_their_own_words(prompt):
    assert source_intent.is_max_owner_question(prompt)


@pytest.mark.parametrize("prompt", [
    "Создай приложение для записи, где клиент заполняет анкету",
    "Нужно поле для записи",
    "Почини меню",
    "Отправил заявку, а результата нет. Исправь это",
    "Подскажи, в чём проблема, и подключи оплату",
    "Сделай кнопку «Почему не работает?»",
    "Добавь раздел «Куда добавить услуги?»",
    "Кнопка с текстом «почему не работает»",
    "Хочу, чтобы если заказа нет, приложение показало каталог",
    "Если товаров нет, покажи сообщение",
    "Сделай так, чтобы меню не открывалось автоматически",
    "Почему нет кнопки? Добавь её в каталог",
    "Продолжи сборку",
    "How does the catalog work? Fix the checkout",
    "Could you add a booking form?",
    "Можешь сделать кнопку оплаты?",
    "Вместо ошибки покажи подтверждение заказа",
    "Почему не работает корзина и настрой оплату",
    "Добавьте запись на приём",
    "Пусть при ошибке появляется кнопка",
    "Когда пользователь нажимает «Сохранить», покажи сообщение об успехе.",
    "When the visitor signs in, show their orders",
    "Когда форма отправлена — открывай корзину",
])
def test_authorised_work_is_not_silently_turned_into_advice(prompt):
    assert not source_intent.is_max_owner_question(prompt)
