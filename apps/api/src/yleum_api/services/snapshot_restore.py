"""Допуск к восстановлению версии: для приложения MAX он закрыт.

Активация MAX требует доказательства совместимости в изолированной среде, без
миграций; нынешний API восстановления ячейки такого договора не даёт. Подменять
его произвольной сборкой манифеста (у которой есть доступ к боевой базе
приложения) нельзя. Рабочее восстановление идёт через `/restorations`.
"""

from __future__ import annotations

from yleum_api.core.errors import ApiError


def ensure_restore_supported(template: str) -> None:
    if template == "max_miniapp":
        raise ApiError(
            "conflict",
            "Восстановление этой версии пока недоступно: среда не прошла "
            "проверку совместимости. Текущая версия сохранена.",
            409,
        )
