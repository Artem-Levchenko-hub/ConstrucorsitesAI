"""Метки Docker на время ребрендинга: пишем обе, читаем любую.

Метку нельзя изменить у запущенного контейнера — только пересоздав его. Поэтому
простое переименование префикса `omnia.` в `yleum.` означало бы, что новая
версия перестаёт видеть все контейнеры, которые сейчас работают у клиентов: их
не остановить, не обновить, не защитить от двойного запуска. Отдельно опасна
`fencing_epoch` — на ней держится защита от двух одновременно живых копий одной
ячейки.

Поэтому переход разбит на две фазы.

**Фаза 1 (эта).** При создании ресурса метки дублируются: рядом с `omnia.<имя>`
пишется `yleum.<имя>` с тем же значением. Всё остальное — сверка личности
ресурса, серверные фильтры Docker, чтения — продолжает работать по старому
префиксу, и это безопасно именно потому, что старый префикс есть теперь у всех:
и у старых ресурсов, и у вновь созданных. Важно, что **ожидаемый** набор меток
(`identity_labels`) в этой фазе не меняется: сверка требует наличия каждой
ожидаемой метки, и добавь мы туда новый префикс — все существующие ресурсы
немедленно получили бы «несовпадение личности».

**Фаза 2 (после полного оборота ячеек).** Когда контейнеров без нового префикса
не останется, ожидания и фильтры переводятся на `yleum.`, а запись старого
префикса прекращается. Чтение старого остаётся навсегда: стоит оно десять строк
и страхует от забытой ячейки.
"""

from __future__ import annotations

from collections.abc import Mapping

NEW_PREFIX = "yleum."
LEGACY_PREFIX = "omnia."


def with_both(labels: Mapping[str, str]) -> dict[str, str]:
    """Возвращает метки, где каждая `omnia.<имя>` продублирована как `yleum.<имя>`.

    Метки с чужими префиксами не трогаются. Если оба имени уже заданы, значение
    под новым префиксом остаётся как есть — оно считается более точным.
    """
    result = dict(labels)
    for key, value in labels.items():
        if key.startswith(LEGACY_PREFIX):
            twin = NEW_PREFIX + key[len(LEGACY_PREFIX) :]
            result.setdefault(twin, value)
    return result


def label_value(labels: Mapping[str, str], suffix: str, default: str | None = None) -> str | None:
    """Значение метки по имени без префикса: сначала `yleum.`, затем `omnia.`.

    Нужно для фазы 2 и для любого кода, который может встретить ресурс, созданный
    уже без старого префикса.
    """
    value = labels.get(NEW_PREFIX + suffix)
    if value is None:
        value = labels.get(LEGACY_PREFIX + suffix)
    return default if value is None else value
