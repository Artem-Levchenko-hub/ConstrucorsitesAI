/**
 * Один словарь на весь кабинет: что случилось → опасно ли → что делать.
 *
 * Одно и то же событие называлось по-разному в трёх местах: «Не удалось
 * проверить готовность», «Статус недоступен», «Не удалось проверить публикацию».
 * Для владельца это тупик: непонятно, виноват ли он, пройдёт ли само и что
 * нажать. Здесь каждая формулировка отвечает на три вопроса сразу и отделяет
 * «связь не удалась» (данные целы, пройдёт само) от «шаг не сделан» (нужно
 * действие владельца).
 */

export type MaxStatusCopy = {
  title: string;
  hint: string;
  /** Подпись кнопки, если в этом месте есть повтор запроса. */
  retry: string;
};

